def build_symbol_window(wb: Workbook) -> None:
    ws = wb.create_sheet("Symbol_Window")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 3, "Symbol Window, NIT, and CAS Timing")

    style_header_row(ws, 3, ["Element", "Duration (macroticks)", "Notes"])
    elements = [
        ("Symbol Window", 150, "Used for clock synchronization via symbols"),
        ("Network Idle Time (NIT)", 1000, "Cluster idle between cycles"),
        ("Collision Arbitration Start (CAS)", 70, "Dynamic slot arbitration period"),
        ("DTS (Data Transfer)", "varies", "Data transmission slot duration"),
    ]

    for i, (elem, duration, notes) in enumerate(elements, start=4):
        ws.cell(row=i, column=1, value=elem)
        ws.cell(row=i, column=2, value=duration)
        ws.cell(row=i, column=3, value=notes)

    stripe_body(ws, 4, 3 + len(elements), 3)
    autosize(ws, {1: 28, 2: 26, 3: 50})


def build_validation_rules(wb: Workbook) -> None:
    ws = wb.create_sheet("Validation_Rules")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 4, "Timing Validation Formulas")

    style_header_row(ws, 3, ["Check ID", "Validation Rule", "Status", "Notes"])
    checks = [
        ("V01", "gdCycle = sum of static slot duration + dynamic segment + symbol window + NIT", "Formula", "Verify cycle closure"),
        ("V02", "Every static frame fits within its assigned slot", "Formula", "Frame length <= slot duration"),
        ("V03", "Every node has at least one slot allocation", "Formula", "No orphan nodes"),
        ("V04", "Dynamic slot count >= dynamic frame count", "Formula", "Sufficient minislots for FIFO"),
        ("V05", "Channel A and B have identical timing structure", "Formula", "Dual-redundancy requirement"),
    ]

    for i, (cid, rule, status, notes) in enumerate(checks, start=4):
        ws.cell(row=i, column=1, value=cid)
        ws.cell(row=i, column=2, value=rule)
        ws.cell(row=i, column=3, value=status)
        ws.cell(row=i, column=4, value=notes)

    stripe_body(ws, 4, 3 + len(checks), 4)
    autosize(ws, {1: 8, 2: 50, 3: 10, 4: 40})


def build_references(wb: Workbook) -> None:
    ws = wb.create_sheet("References")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 2, "References")

    refs = [
        "ISO 17458-1 FlexRay Requirements Specification",
        "ISO 17458-3 FlexRay Protocol Specification",
        "ISO 17458-5 FlexRay Electrical Specification",
        "FIBEX FlexRay XML Schema",
    ]

    for i, ref in enumerate(refs, start=3):
        ws.cell(row=i, column=1, value=ref).font = body_font()

    autosize(ws, {1: 70})


def generate(input_path: str, output_path: str) -> dict:
    with open(input_path) as f:
        data = json.load(f)

    cluster = data.get("cluster", {})
    timing = data.get("timing", {})
    channel_a = data.get("channel_a", {"speed_mbps": 10})
    channel_b = data.get("channel_b", {"speed_mbps": 10})
    nodes = data.get("nodes", [])
    frames = data.get("frames", [])
    static_slots = data.get("static_slots", [])
    dynamic_slots = data.get("dynamic_slots", [])

    wb = Workbook()
    wb.remove(wb.active)

    build_title_page(wb, cluster)
    build_doc_control(wb)
    build_cluster_parameters(wb, timing)
    build_channel_config(wb, channel_a, channel_b)
    build_node_inventory(wb, nodes)
    build_frame_catalog(wb, frames)
    build_static_slots(wb, static_slots)
    build_dynamic_slots(wb, dynamic_slots)
    build_symbol_window(wb)
    build_validation_rules(wb)
    build_references(wb)

    wb.active = 0
    wb.save(output_path)

    return {
        "cluster_name": cluster.get("name", ""),
        "num_nodes": len(nodes),
        "num_frames": len(frames),
        "num_static_slots": len(static_slots),
        "num_dynamic_minislots": len(dynamic_slots),
        "output_path": output_path,
    }


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python generate_flexray.py <input.json> <output.xlsx>", file=sys.stderr)
        sys.exit(2)
    summary = generate(sys.argv[1], sys.argv[2])
    print(json.dumps(summary, indent=2))
