def build_triggering_conditions(wb, triggering):
    ws = wb.create_sheet("07_Triggering_Conditions")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 4, "Triggering Conditions Catalog")

    categories = ["environmental", "sensor", "road_user", "system_state", "driver_state", "combined"]
    row = 3
    for cat in categories:
        items = triggering.get(cat, [])
        style_title_row(ws, row, 4, f"{cat.replace('_', ' ').title()} Triggering Conditions")
        row += 1
        style_header_row(ws, row, ["Condition ID", "Description", "Likelihood", "Notes"])
        row += 1
        for item in items:
            ws.cell(row=row, column=1, value=item.get("id", ""))
            ws.cell(row=row, column=2, value=item.get("description", ""))
            ws.cell(row=row, column=3, value=item.get("likelihood", ""))
            ws.cell(row=row, column=4, value="")
            row += 1
        row += 1
    autosize(ws, {1: 14, 2: 50, 3: 14, 4: 30})


