"""
SOTIF Analysis Builder — generates a multi-tab ISO 21448 SOTIF analysis workbook.

Usage:
    python generate_sotif_analysis.py <input.json> <output.xlsx>

Input JSON schema:
{
  "system": {name, abbr, project, doc_id, revision, date, author},
  "functions": [{id, name, description, kinetic_authority}],
  "odd_definition": {
    "scenery": [{code, category, description}],
    "environment": [{code, category, description}],
    "dynamic_elements": [{code, category, description}],
    "driver_state": [{code, category, description}]
  },
  "performance_limitations": [{function_id, limitation_id, description, sensor_type, impact_summary}],
  "functional_insufficiencies": [{insufficiency_id, function_id, type, description, root_cause}],
  "triggering_conditions": {
    "environmental": [...],
    "sensor": [...],
    "road_user": [...],
    "system_state": [...],
    "driver_state": [...],
    "combined": [...]
  },
  "hazardous_behaviors": [{function_id, insufficiency_id, triggering_condition_id, hazard_description, severity}],
  "scenarios": [{scenario_id, function_id, insufficiency_id, triggering_condition_ids, quadrant, evidence}],
  "acceptance_criteria": [{safety_goal_id, function_id, criterion_description, threshold, unit, rationale}]
}
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

FONT_NAME = "Calibri"
NAVY = "1F3864"
LIGHT_BLUE = "D9E2F3"
ALT_ROW = "F2F2F2"
WARN_YELLOW = "FFF2CC"
GREEN_OK = "C6EFCE"

THIN = Side(border_style="thin", color="BFBFBF")
BORDER_ALL = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def title_font(size=16):
    return Font(name=FONT_NAME, size=size, bold=True, color="FFFFFF")


def header_font():
    return Font(name=FONT_NAME, size=11, bold=True, color="FFFFFF")


def body_font():
    return Font(name=FONT_NAME, size=10)


def style_title_row(ws, row, last_col, text):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=last_col)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = title_font(14)
    cell.fill = PatternFill("solid", fgColor=NAVY)
    cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = 28


def style_header_row(ws, row, headers):
    for col, h in enumerate(headers, start=1):
        cell = ws.cell(row=row, column=col, value=h)
        cell.font = header_font()
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_ALL
    ws.row_dimensions[row].height = 32


def stripe_body(ws, start_row, end_row, last_col):
    for r in range(start_row, end_row + 1):
        fill = PatternFill("solid", fgColor=ALT_ROW) if (r - start_row) % 2 else None
        for c in range(1, last_col + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = body_font()
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER_ALL
            if fill:
                cell.fill = fill


def autosize(ws, widths):
    for col, width in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = width


def build_title_page(wb, system):
    ws = wb.create_sheet("00_Title_Page")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 2, 4, "ISO 21448 SOTIF Analysis")
    style_title_row(ws, 3, 4, f"{system.get('name', '')} ({system.get('abbr', '')})")

    fields = [
        ("Project", system.get("project", "")),
        ("Document ID", system.get("doc_id", "")),
        ("Revision", system.get("revision", "")),
        ("Date", system.get("date", "")),
        ("Author", system.get("author", "")),
        ("Standard", "ISO 21448:2022, Safety of the Intended Functionality"),
    ]
    row = 6
    for label, value in fields:
        ws.cell(row=row, column=2, value=label).font = Font(name=FONT_NAME, size=11, bold=True, color=NAVY)
        ws.cell(row=row, column=3, value=value).font = body_font()
        row += 1
    autosize(ws, {1: 4, 2: 22, 3: 60, 4: 4})


def build_doc_control(wb):
    ws = wb.create_sheet("01_Document_Control")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 5, "Document Control")
    style_header_row(ws, 3, ["Revision", "Date", "Author", "Description", "Approver"])
    rows = [("0.1", "", "", "Initial draft generated by sotif-analysis-builder", ""), ("1.0", "", "", "Released", "")]
    for i, data in enumerate(rows, start=4):
        for c, val in enumerate(data, start=1):
            ws.cell(row=i, column=c, value=val)
    stripe_body(ws, 4, 5, 5)
    autosize(ws, {1: 12, 2: 14, 3: 22, 4: 50, 5: 22})


def build_item_definition(wb):
    ws = wb.create_sheet("02_Item_Definition_Reference")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 5, "Item Definition Reference")
    ws.merge_cells("A3:E3")
    ws.cell(row=3, column=1, value="Reference: Link to upstream item definition document.").font = Font(name=FONT_NAME, italic=True)
    autosize(ws, {1: 4, 2: 22, 3: 60, 4: 22, 5: 22})


def build_functional_perf_spec(wb, functions):
    ws = wb.create_sheet("03_Functional_Perf_Spec")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 6, "Functional Performance Specification")
    style_header_row(ws, 3, ["Function ID", "Function Name", "Intended Behavior", "Performance Envelope", "ODD Constraints", "Kinetic Authority"])
    for i, f in enumerate(functions, start=4):
        ws.cell(row=i, column=1, value=f.get("id", ""))
        ws.cell(row=i, column=2, value=f.get("name", ""))
        ws.cell(row=i, column=3, value=f.get("description", ""))
        ws.cell(row=i, column=4, value="<TBD: sensor range, latency, confidence threshold>")
        ws.cell(row=i, column=5, value="<TBD: speed range, road type, weather>")
        ws.cell(row=i, column=6, value=(f.get("kinetic_authority") or "medium").lower())
    stripe_body(ws, 4, 3 + len(functions), 6)
    autosize(ws, {1: 12, 2: 24, 3: 50, 4: 40, 5: 40, 6: 16})


def build_odd_definition(wb, odd_def):
    ws = wb.create_sheet("04_ODD_Definition")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 5, "Operational Design Domain (ODD) Definition")

    sections = [
        ("Scenery", odd_def.get("scenery", [])),
        ("Environment", odd_def.get("environment", [])),
        ("Dynamic Elements", odd_def.get("dynamic_elements", [])),
        ("Driver State", odd_def.get("driver_state", [])),
    ]
    row = 3
    for section_name, items in sections:
        style_title_row(ws, row, 5, section_name)
        row += 1
        style_header_row(ws, row, ["Code", "Category", "Description"])
        row += 1
        for item in items:
            ws.cell(row=row, column=1, value=item.get("code", ""))
            ws.cell(row=row, column=2, value=item.get("category", ""))
            ws.cell(row=row, column=3, value=item.get("description", ""))
            row += 1
        row += 1
    autosize(ws, {1: 8, 2: 20, 3: 60, 4: 20, 5: 20})


