"""
Automotive Ethernet Network Configuration Generator per IEEE 100BASE-T1 / 1000BASE-T1.

Generates a multi-tab xlsx with network topology, VLAN configuration, SOME/IP service
catalog, switch forwarding tables, AVB stream allocation, TSN scheduling, and validation.

Usage:
    python generate_autoeth.py <input.json> <output.xlsx>

Input JSON schema:
{
  "network": {name, doc_id, revision, date, author, approver, company},
  "topology": {
    "switches": [{id, name, ports, backplane_bandwidth_gbps}],
    "ecus": [{id, name, vlans, services}],
    "links": [{from, to, bandwidth_mbps, phy_type}]
  },
  "vlans": [{vlan_id, name, priority, isolate}],
  "services": [{service_id, name, method_ids, event_ids, provider_id, consumer_ids}],
  "avb_streams": [{talker_id, listener_ids, bandwidth_mbps, traffic_class}],
  "multicast": [{group_address, sources, listeners}]
}
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter


FONT_NAME = "Calibri"
NAVY = "1F3864"
LIGHT_BLUE = "D9E2F3"
ALT_ROW = "F2F2F2"
WARN_YELLOW = "FFF2CC"
GREEN_OK = "C6EFCE"
RED_BAD = "F8CBAD"

THIN = Side(border_style="thin", color="BFBFBF")
BORDER_ALL = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def title_font(size: int = 16) -> Font:
    return Font(name=FONT_NAME, size=size, bold=True, color="FFFFFF")


def header_font() -> Font:
    return Font(name=FONT_NAME, size=11, bold=True, color="FFFFFF")


def body_font() -> Font:
    return Font(name=FONT_NAME, size=10)


def style_title_row(ws, row: int, last_col: int, text: str) -> None:
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=last_col)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = title_font(14)
    cell.fill = PatternFill("solid", fgColor=NAVY)
    cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = 28


def style_header_row(ws, row: int, headers: list[str]) -> None:
    for col, h in enumerate(headers, start=1):
        cell = ws.cell(row=row, column=col, value=h)
        cell.font = header_font()
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_ALL
    ws.row_dimensions[row].height = 32


def stripe_body(ws, start_row: int, end_row: int, last_col: int) -> None:
    for r in range(start_row, end_row + 1):
        fill = PatternFill("solid", fgColor=ALT_ROW) if (r - start_row) % 2 else None
        for c in range(1, last_col + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = body_font()
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER_ALL
            if fill:
                cell.fill = fill


def autosize(ws, widths: dict[int, int]) -> None:
    for col, width in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = width


def build_title_page(wb: Workbook, network: dict) -> None:
    ws = wb.create_sheet("Title_Page")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 2, 4, "Automotive Ethernet Network Configuration")
    style_title_row(ws, 3, 4, network.get("name", ""))

    fields = [
        ("Network Name", network.get("name", "")),
        ("Document ID", network.get("doc_id", "")),
        ("Revision", network.get("revision", "")),
        ("Date", network.get("date", "")),
        ("Author", network.get("author", "")),
        ("Approver", network.get("approver", "")),
        ("Company", network.get("company", "")),
        ("Standard", "IEEE 100BASE-T1 / 1000BASE-T1 / AUTOSAR Ethernet"),
        ("Network Type", "High-Bandwidth In-Vehicle, SOME/IP + AVB/TSN"),
    ]

    row = 6
    for label, value in fields:
        ws.cell(row=row, column=2, value=label).font = Font(name=FONT_NAME, size=11, bold=True, color=NAVY)
        ws.cell(row=row, column=3, value=value).font = body_font()
        ws.cell(row=row, column=3).alignment = Alignment(horizontal="left")
        row += 1

    autosize(ws, {1: 4, 2: 22, 3: 60, 4: 4})


def build_doc_control(wb: Workbook) -> None:
    ws = wb.create_sheet("Document_Control")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 1, 5, "Document Control")
    style_header_row(ws, 3, ["Revision", "Date", "Author", "Description of change", "Approver"])
    placeholders = [
        ("0.1", "", "", "Initial network configuration generated by automotive-ethernet-builder", ""),
        ("0.2", "", "", "VLAN and SOME/IP service allocation", ""),
        ("1.0", "", "", "Released for EMC and integration testing", ""),
    ]
    for i, row_data in enumerate(placeholders, start=4):
        for col, val in enumerate(row_data, start=1):
            ws.cell(row=i, column=col, value=val)
    stripe_body(ws, 4, 4 + len(placeholders) - 1, 5)
    autosize(ws, {1: 12, 2: 14, 3: 22, 4: 50, 5: 22})


def build_network_topology(wb: Workbook, topology: dict) -> None:
    ws = wb.create_sheet("Network_Topology")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 6, "Network Topology — Switches, ECUs, Links")

    # Switches
    style_header_row(ws, 3, ["Switch ID", "Switch Name", "Ports", "Backplane Bandwidth (Gbps)", "Role", "Notes"])
    switches = topology.get("switches", [])
    if not switches:
        switches = [
            {"id": "SW01", "name": "Central Switch", "ports": 8, "backplane_gbps": 10},
        ]

    for i, sw in enumerate(switches, start=4):
        ws.cell(row=i, column=1, value=sw.get("id", ""))
        ws.cell(row=i, column=2, value=sw.get("name", ""))
        ws.cell(row=i, column=3, value=sw.get("ports", 0))
        ws.cell(row=i, column=4, value=sw.get("backplane_gbps", 0))
        ws.cell(row=i, column=5, value="Core" if sw.get("id") == "SW01" else "Edge")
        ws.cell(row=i, column=6, value="")

    stripe_body(ws, 4, 3 + len(switches), 6)

    # Links
    base = 4 + len(switches) + 2
    style_header_row(ws, base, ["From", "To", "Bandwidth (Mbps)", "PHY Type", "Status"])
    links = topology.get("links", [])
    for i, link in enumerate(links, start=base + 1):
        ws.cell(row=i, column=1, value=link.get("from", ""))
        ws.cell(row=i, column=2, value=link.get("to", ""))
        ws.cell(row=i, column=3, value=link.get("bandwidth_mbps", 100))
        ws.cell(row=i, column=4, value=link.get("phy_type", "100BASE-T1"))
        ws.cell(row=i, column=5, value="Active")

    stripe_body(ws, base + 1, base + len(links), 5)
    autosize(ws, {1: 10, 2: 20, 3: 10, 4: 14, 5: 12, 6: 24})


