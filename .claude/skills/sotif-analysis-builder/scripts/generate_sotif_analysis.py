def generate(input_path, output_path):
    with open(input_path) as f:
        data = json.load(f)

    system = data.get("system", {})
    functions = data.get("functions", [])
    if not functions:
        raise ValueError("Input must include functions.")

    wb = Workbook()
    wb.remove(wb.active)

    build_title_page(wb, system)
    build_doc_control(wb)
    build_item_definition(wb)
    build_functional_perf_spec(wb, functions)
    build_odd_definition(wb, data.get("odd_definition", {}))
    build_perf_limitations(wb, data.get("performance_limitations", []))
    build_functional_insufficiencies(wb, data.get("functional_insufficiencies", []))
    build_triggering_conditions(wb, data.get("triggering_conditions", {}))
    build_hazardous_behaviors(wb, data.get("hazardous_behaviors", []))
    build_scenario_classification(wb, data.get("scenarios", []))
    build_acceptance_criterion(wb, data.get("acceptance_criteria", []))
    build_references(wb)

    wb.active = 0
    wb.save(output_path)

    return {
        "system": system.get("name", ""),
        "functions": len(functions),
        "performance_limitations": len(data.get("performance_limitations", [])),
        "functional_insufficiencies": len(data.get("functional_insufficiencies", [])),
        "scenarios": len(data.get("scenarios", [])),
        "acceptance_criteria": len(data.get("acceptance_criteria", [])),
        "tabs": 12,
        "output_path": output_path,
    }


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python generate_sotif_analysis.py <input.json> <output.xlsx>", file=sys.stderr)
        sys.exit(2)
    summary = generate(sys.argv[1], sys.argv[2])
    print(json.dumps(summary, indent=2))
