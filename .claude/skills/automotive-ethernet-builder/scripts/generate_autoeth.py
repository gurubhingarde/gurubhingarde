def generate(input_path: str, output_path: str) -> dict:
    with open(input_path) as f:
        data = json.load(f)

    network = data.get("network", {})
    topology = data.get("topology", {})
    vlans = data.get("vlans", [])
    services = data.get("services", [])
    streams = data.get("avb_streams", [])

    wb = Workbook()
    wb.remove(wb.active)

    build_title_page(wb, network)
    build_doc_control(wb)
    build_network_topology(wb, topology)
    build_vlan_config(wb, vlans)
    build_switch_config(wb)
    build_someip_catalog(wb, services)
    build_avb_streams(wb, streams)
    build_tsn_scheduling(wb)
    build_multicast_routing(wb)
    build_validation(wb)
    build_references(wb)

    wb.active = 0
    wb.save(output_path)

    return {
        "network_name": network.get("name", ""),
        "num_vlans": len(vlans),
        "num_services": len(services),
        "num_avb_streams": len(streams),
        "output_path": output_path,
    }


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python generate_autoeth.py <input.json> <output.xlsx>", file=sys.stderr)
        sys.exit(2)
    summary = generate(sys.argv[1], sys.argv[2])
    print(json.dumps(summary, indent=2))
