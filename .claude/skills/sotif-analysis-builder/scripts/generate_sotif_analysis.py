def build_scenario_classification(wb, scenarios):
    ws = wb.create_sheet("09_Scenario_Quadrants")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 8, "Scenario Quadrant Classification (ISO 21448 §5)")

    note = ws.cell(row=2, column=1,
                   value="Four quadrants: Known Safe (function works as designed, outcome is safe); "
                         "Known Unsafe (function fails, outcome is hazardous, identified & mitigated); "
                         "Unknown Safe (unknown scenario, outcome happens to be safe); "
                         "Unknown Unsafe (unknown scenario, outcome is hazardous — residual risk acceptance target).")
    note.font = Font(name=FONT_NAME, italic=True, size=9)
    note.fill = PatternFill("solid", fgColor=WARN_YELLOW)
    ws.merge_cells("A2:H2")
    ws.row_dimensions[2].height = 40

    style_header_row(ws, 4, ["Scenario ID", "Function", "Insufficiency + Trigger", "Quadrant", "Evidence / Basis", "Residual Risk", "Mitigation / V&V", "Notes"])
    for i, s in enumerate(scenarios, start=5):
        ws.cell(row=i, column=1, value=s.get("scenario_id", ""))
        ws.cell(row=i, column=2, value=s.get("function_id", ""))
        ws.cell(row=i, column=3, value=f"{s.get('insufficiency_id', '')} + {s.get('triggering_condition_ids', '')}")
        ws.cell(row=i, column=4, value=s.get("quadrant", ""))
        ws.cell(row=i, column=5, value=s.get("evidence", ""))
        ws.cell(row=i, column=6, value="<TBD>")
        ws.cell(row=i, column=7, value="<TBD>")
        ws.cell(row=i, column=8, value="")
    stripe_body(ws, 5, 4 + len(scenarios), 8)
    autosize(ws, {1: 14, 2: 14, 3: 40, 4: 16, 5: 40, 6: 16, 7: 30, 8: 20})


