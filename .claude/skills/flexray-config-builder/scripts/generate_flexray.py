"""
FlexRay Cluster Configuration Generator per ISO 17458.

Generates a multi-tab xlsx with cluster timing parameters, node/frame catalogs,
static and dynamic slot allocation, dual-channel A/B config, and validation rules.

Usage:
    python generate_flexray.py <input.json> <output.xlsx>

Input JSON schema:
{
  "cluster": {name, doc_id, revision, date, author, approver, company},
  "timing": {gdCycle_ms, gdMacrotick_us, gMacroPerCycle, gNumberOfStaticSlots, gNumberOfMinislots},
  "channel_a": {speed_mbps, duplex},
  "channel_b": {speed_mbps, duplex},
  "nodes": [{ecu_id, name, cluster_node_id, nr_controller, rx_enabled, tx_enabled}],
  "frames": [{frame_id, name, data_length_bytes, priority, channel_a, channel_b}],
  "static_slots": [{slot_id, node_id, frame_id, transmission_mode}],
  "dynamic_slots": [{minislot_id, node_ids, frame_ids, transmission_mode}]
}
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo


FONT_NAME = "Calibri"
NAVY = "1F3864"
LIGHT_BLUE = "D9E2F3"
ALT_ROW = "F2F2F2"
WARN_YELLOW = "FFF2CC"
GREEN_OK = "C6EFCE"
RED_BAD = "F8CBAD"

THIN = Side(border_style="thin", color="BFBFBF")
BORDER_ALL = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def title_font(size: int = 16) -> Font:
    return Font(name=FONT_NAME, size=size, bold=True, color="FFFFFF")


def header_font() -> Font:
    return Font(name=FONT_NAME, size=11, bold=True, color="FFFFFF")


def body_font() -> Font:
    return Font(name=FONT_NAME, size=10)


def style_title_row(ws, row: int, last_col: int, text: str) -> None:
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=last_col)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = title_font(14)
    cell.fill = PatternFill("solid", fgColor=NAVY)
    cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = 28


def style_header_row(ws, row: int, headers: list[str]) -> None:
    for col, h in enumerate(headers, start=1):
        cell = ws.cell(row=row, column=col, value=h)
        cell.font = header_font()
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_ALL
    ws.row_dimensions[row].height = 32


def stripe_body(ws, start_row: int, end_row: int, last_col: int) -> None:
    for r in range(start_row, end_row + 1):
        fill = PatternFill("solid", fgColor=ALT_ROW) if (r - start_row) % 2 else None
        for c in range(1, last_col + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = body_font()
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER_ALL
            if fill:
                cell.fill = fill


def autosize(ws, widths: dict[int, int]) -> None:
    for col, width in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = width


def build_title_page(wb: Workbook, cluster: dict) -> None:
    ws = wb.create_sheet("Title_Page")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 2, 4, "FlexRay Cluster Configuration")
    style_title_row(ws, 3, 4, cluster.get("name", ""))

    fields = [
        ("Cluster Name", cluster.get("name", "")),
        ("Document ID", cluster.get("doc_id", "")),
        ("Revision", cluster.get("revision", "")),
        ("Date", cluster.get("date", "")),
        ("Author", cluster.get("author", "")),
        ("Approver", cluster.get("approver", "")),
        ("Company", cluster.get("company", "")),
        ("Standard", "ISO 17458 FlexRay Specification"),
        ("Network Type", "Time-Triggered + Event-Triggered, Dual Channel A/B"),
    ]

    row = 6
    for label, value in fields:
        ws.cell(row=row, column=2, value=label).font = Font(name=FONT_NAME, size=11, bold=True, color=NAVY)
        ws.cell(row=row, column=3, value=value).font = body_font()
        ws.cell(row=row, column=3).alignment = Alignment(horizontal="left")
        row += 1

    autosize(ws, {1: 4, 2: 22, 3: 60, 4: 4})


def build_doc_control(wb: Workbook) -> None:
    ws = wb.create_sheet("Document_Control")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 1, 5, "Document Control")
    style_header_row(ws, 3, ["Revision", "Date", "Author", "Description of change", "Approver"])
    placeholders = [
        ("0.1", "", "", "Initial configuration generated by flexray-config-builder skill", ""),
        ("0.2", "", "", "Timing validation and optimization", ""),
        ("1.0", "", "", "Released for testing", ""),
    ]
    for i, row_data in enumerate(placeholders, start=4):
        for col, val in enumerate(row_data, start=1):
            ws.cell(row=i, column=col, value=val)
    stripe_body(ws, 4, 4 + len(placeholders) - 1, 5)
    autosize(ws, {1: 12, 2: 14, 3: 22, 4: 50, 5: 22})


def build_cluster_parameters(wb: Workbook, timing: dict) -> None:
    ws = wb.create_sheet("Cluster_Parameters")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 3, "Cluster Timing Parameters")

    style_header_row(ws, 3, ["Parameter", "Value", "Unit / Description"])
    params = [
        ("gdCycle", timing.get("gdCycle_ms", 5), "ms — Communication cycle duration"),
        ("gdMacrotick", timing.get("gdMacrotick_us", 1), "us — Smallest time unit"),
        ("gMacroPerCycle", timing.get("gMacroPerCycle", 5000), "macroticks — Macroticks per cycle"),
        ("gNumberOfStaticSlots", timing.get("gNumberOfStaticSlots", 10), "slots — Static segment slot count"),
        ("gNumberOfMinislots", timing.get("gNumberOfMinislots", 50), "minislots — Dynamic segment minislots"),
        ("gdActionPointOffset", 3, "macroticks — Action point after slot start"),
        ("gdNIT", timing.get("gdNIT_macroticks", 1000), "macroticks — Network Idle Time"),
        ("gdStaticSlot", timing.get("gdStaticSlot_macroticks", 640), "macroticks — Static slot duration"),
    ]

    for i, (param, value, desc) in enumerate(params, start=4):
        ws.cell(row=i, column=1, value=param).font = Font(name=FONT_NAME, bold=True, size=10)
        ws.cell(row=i, column=2, value=value).font = body_font()
        ws.cell(row=i, column=3, value=desc).font = body_font()

    stripe_body(ws, 4, 3 + len(params), 3)
    autosize(ws, {1: 24, 2: 14, 3: 50})


def build_channel_config(wb: Workbook, channel_a: dict, channel_b: dict) -> None:
    ws = wb.create_sheet("Channel_Config")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 5, "Channel A/B Physical Layer Configuration")

    style_header_row(ws, 3, ["Channel", "Link Speed (Mbps)", "Duplex Mode", "Status", "Notes"])
    rows = [
        ("A", channel_a.get("speed_mbps", 10), channel_a.get("duplex", "Full"), "Active", "Time-Triggered"),
        ("B", channel_b.get("speed_mbps", 10), channel_b.get("duplex", "Full"), "Active", "Event-Triggered / Redundancy"),
    ]
    for i, (ch, spd, duplex, status, notes) in enumerate(rows, start=4):
        ws.cell(row=i, column=1, value=ch)
        ws.cell(row=i, column=2, value=spd)
        ws.cell(row=i, column=3, value=duplex)
        ws.cell(row=i, column=4, value=status)
        ws.cell(row=i, column=5, value=notes)

    stripe_body(ws, 4, 4 + len(rows) - 1, 5)
    autosize(ws, {1: 10, 2: 16, 3: 14, 4: 12, 5: 30})


def build_node_inventory(wb: Workbook, nodes: list[dict]) -> None:
    ws = wb.create_sheet("Node_Inventory")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 6, "Node (ECU) Inventory")

    style_header_row(ws, 3, ["Node ID", "ECU Name", "Cluster Node ID", "NR Controller", "RX Enabled", "TX Enabled"])
    if not nodes:
        nodes = [
            {"ecu_id": "N01", "name": "PowerECU", "cluster_node_id": 0, "nr_controller": "Yes", "rx_enabled": True, "tx_enabled": True},
            {"ecu_id": "N02", "name": "SafetyECU", "cluster_node_id": 1, "nr_controller": "No", "rx_enabled": True, "tx_enabled": True},
        ]

    for i, node in enumerate(nodes, start=4):
        ws.cell(row=i, column=1, value=node.get("ecu_id", ""))
        ws.cell(row=i, column=2, value=node.get("name", ""))
        ws.cell(row=i, column=3, value=node.get("cluster_node_id", ""))
        ws.cell(row=i, column=4, value="Yes" if node.get("nr_controller") else "No")
        ws.cell(row=i, column=5, value="Yes" if node.get("rx_enabled") else "No")
        ws.cell(row=i, column=6, value="Yes" if node.get("tx_enabled") else "No")

    stripe_body(ws, 4, 3 + len(nodes), 6)
    autosize(ws, {1: 10, 2: 20, 3: 16, 4: 14, 5: 12, 6: 12})


